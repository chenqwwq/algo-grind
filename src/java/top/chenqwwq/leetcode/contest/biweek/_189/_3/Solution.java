package top.chenqwwq.leetcode.contest.biweek._189._3;

/**
 * 力扣 4022「无限字符串里第 K 个数字」/ 双周赛 189 T3
 *
 * 序列构造:
 *   块 b 覆盖 [10b, 10b+9] 共 10 个连续整数,块内拼接顺序由 b 的奇偶决定:
 *     - b 为偶数:按递增附加,即 10b, 10b+1, ..., 10b+9
 *     - b 为奇数:按递减附加,即 10b+9, 10b+8, ..., 10b
 *   所有块按 b = 0, 1, 2, ... 依次拼接成无限字符串。
 *
 * 注意块 0 的特殊性:题目要求拼接的是正整数,块 0 覆盖 [0, 9],其中 0 被排除,
 * 只保留 1~9,因此字符串开头是 "123456789" 而不是 "0123456789"。
 *
 * 序列开头几块:
 *   块0(偶):123456789
 *   块1(奇):19 18 17 16 15 14 13 12 11 10 → "19181716151413121110"
 *   块2(偶):20 21 22 ... 29                 → "20212223242526272829"
 *   块3(奇):39 38 37 ... 30                 → "39383736353433323130"
 *
 * 解法(分位数区间定位,不枚举):
 *   每个块的字符数 = 块内数字位数 × 10。对 d 位数区间:
 *     - b ∈ [10^{d-2}, 10^{d-1}-1],共 9*10^{d-2} 个块
 *     - 每块长 10*d,故区间总长 9*d*10^{d-1}
 *   先确定第 k 位落在几位数区间,再在区间内定位到具体块和块内偏移。
 *
 * 复杂度:O(位数),空间 O(1)
 *
 * @author chenqwwq
 */
public class Solution {
    public int kthDigit(long k) {
        // ================== 第一步:1 位数区间(1~9,共 9 位) ==================
        // 字符串最前面 9 个字符就是数字 1 到 9,一一对应,直接返回 k 本身。
        // 例:k=4 → 第 4 位是 '4';k=9 → 第 9 位是 '9'。
        if (k <= 9)
            return (int) (k);

        // k 越过 1 位数区间:减去前 9 位,此后 k 表示「从块 b=1(首个 2 位数块)开始数的第几位」。
        // 例:k=10 → k=1,即块 1 的第 1 位;块 1 以递减开头,首位是数字 19 的 '1'。
        k -= 9;

        // ================== 第二步:逐层减 d 位数区间总长,确定 k 落在几位数区间 ==================
        // d = 当前判断的位数,从 2 位数开始。
        long d = 2;
        while (true) {
            // 当前 d 位数区间的总字符数:
            //   块数 = 9 * 10^(d-2)   (b 从 10^(d-2) 到 10^(d-1)-1)
            //   每块长 = 10 * d       (块内 10 个数 × 每个 d 位)
            //   总长 = 9 * 10^(d-2) * 10d = 9 * d * 10^(d-1)
            long len = 9L * d * pow10((int) (d - 1));
            if (k > len) {
                // k 落在位数更多的区间里:扣掉整段 d 位数区间,继续考察 d+1 位数
                k -= len;
                d++;
            } else {
                // k 落在当前 d 位数区间内,退出循环
                break;
            }
        }
        // 循环结束后:k 表示「d 位数区间内的第几位」(1-based,范围 [1, 区间总长])。

        // ================== 第三步:在 d 位数区间内定位到具体块 b 和块内偏移 ==================
        long blockLen = 10L * d;                  // 每个块固定 10 个数 × d 位 = 10*d 个字符
        long blockIndex = (k - 1) / blockLen;     // 区间内第几个块,0-based(第 0 个、第 1 个 ...)
        long offset = (k - 1) % blockLen;         // 落在块内的字符偏移,0-based,范围 [0, 10*d-1]
        long b = pow10((int) (d - 2)) + blockIndex; // 真实块编号:d 位数区间的起始块是 10^(d-2)

        // ================== 第四步:块内定位到具体数字与数位 ==================
        // 块内共 10 个数字、每个 d 位。offset 除以 d 得数字序号,对 d 取余得该数字内的位偏移。
        int j = (int) (offset / d);      // 块内第 j 个数字,0-based,范围 [0, 9]
        int idx = (int) (offset % d);    // 该数字的第 idx 位,0-based 从左往右数,范围 [0, d-1]

        // 块内第 j 个位置对应的真实数字,由 b 的奇偶决定:
        //   b 偶:块内按递增排列 → 第 j 个数 = 10b + j       (10b, 10b+1, ..., 10b+9)
        //   b 奇:块内按递减排列 → 第 j 个数 = 10b + 9 - j   (10b+9, 10b+8, ..., 10b)
        long num = (b & 1) == 0 ? 10 * b + j : 10 * b + 9 - j;

        // 取出 num 从左数第 idx 位:
        //   先除以 10^(d-1-idx) 把目标位移动到个位,再对 10 取余得到该位数字。
        //   例:num=19, d=2, idx=1 → 19 / 10^(2-1-1)=19 / 10^0=19, 19 % 10 = 9 ✓
        return (int) ((num / pow10((int) (d - 1 - idx))) % 10);
    }

    /**
     * 计算 10^e。
     * 用循环乘法实现,避免 Math.pow 的浮点精度问题和 double 转换。
     */
    private long pow10(int e) {
        long r = 1;
        while (e-- > 0) {
            r *= 10;
        }
        return r;
    }

    public static void main(String[] args) {
        Solution s = new Solution();
        // 官方示例:k=4→4, k=15→7, k=11→9
        System.out.println(s.kthDigit(4));
        System.out.println(s.kthDigit(15));
        System.out.println(s.kthDigit(11));
    }
}
